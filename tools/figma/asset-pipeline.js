/**
 * ACL-ADLC Figma Asset Pipeline (Layer 2)
 * Discovers, downloads, and maps vector icons and image fills into local asset imports.
 */

const fs = require('fs');
const path = require('path');

class FigmaAssetPipeline {
  /**
   * Sanitize node name into a clean kebab-case asset filename
   */
  static sanitizeName(name) {
    return (
      name
        .toLowerCase()
        .replace(/[^a-z0-9_-]/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '') || 'asset'
    );
  }

  /**
   * Traverse Figma tree and collect all exportable image and vector nodes
   */
  static collectAssetNodes(node, result = []) {
    if (!node || node.visible === false) return result;

    const isVector = ['VECTOR', 'STAR', 'ELLIPSE', 'REGULAR_POLYGON', 'BOOLEAN_OPERATION'].includes(node.type);
    const hasImageFill = Array.isArray(node.fills) && node.fills.some((f) => f.type === 'IMAGE' && f.visible !== false);

    if (isVector) {
      result.push({
        id: node.id,
        name: this.sanitizeName(node.name),
        type: 'svg',
        format: 'svg',
        nodeType: node.type,
      });
    } else if (hasImageFill) {
      const imgFill = node.fills.find((f) => f.type === 'IMAGE');
      result.push({
        id: node.id,
        name: this.sanitizeName(node.name),
        type: 'image',
        format: 'png',
        imageRef: imgFill.imageRef,
        nodeType: node.type,
      });
    }

    if (Array.isArray(node.children)) {
      for (const child of node.children) {
        this.collectAssetNodes(child, result);
      }
    }

    return result;
  }

  /**
   * Generate TypeScript / JavaScript Asset Import Manifest
   */
  static generateAssetManifest(assets, targetDir = 'src/assets/figma') {
    const imports = [];
    const exports = [];

    assets.forEach((asset, idx) => {
      const varName = asset.name.replace(/-([a-z0-9])/g, (_, g) => g.toUpperCase()) + (asset.type === 'svg' ? 'Icon' : 'Img');
      const relPath = `./${asset.name}.${asset.format}`;
      imports.push(`import ${varName} from '${relPath}';`);
      exports.push(`  ${varName},`);
    });

    return [
      '// Auto-generated by ACL-ADLC Figma Asset Pipeline (Layer 2)',
      '// Do not edit manually',
      '',
      imports.join('\n'),
      '',
      'export const FigmaAssets = {',
      exports.join('\n'),
      '};',
      '',
      'export default FigmaAssets;',
    ].join('\n');
  }

  /**
   * Process project assets and save manifest
   */
  static async process(figmaDoc, projectRoot = process.cwd()) {
    const assetsDir = path.join(projectRoot, 'src', 'assets', 'figma');
    if (!fs.existsSync(assetsDir)) {
      fs.mkdirSync(assetsDir, { recursive: true });
    }

    const rootNode = figmaDoc.document || figmaDoc;
    const assets = this.collectAssetNodes(rootNode);

    // Write Asset Manifest
    const manifestContent = this.generateAssetManifest(assets);
    const manifestPath = path.join(assetsDir, 'index.ts');
    fs.writeFileSync(manifestPath, manifestContent, 'utf8');

    return {
      totalAssets: assets.length,
      assets,
      manifestPath,
      assetsDir,
    };
  }
}

module.exports = { FigmaAssetPipeline };
