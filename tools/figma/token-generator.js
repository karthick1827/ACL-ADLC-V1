/**
 * ACL-ADLC Design Tokens & Theme Generator (Layer 4)
 * Extracts typography scales, color palettes, gradients, and shadows into theme.css & Tailwind config.
 */

const { FigmaCompiler } = require('./figma-compiler');

class FigmaTokenGenerator {
  /**
   * Extract unique colors, gradients, typography, and shadows across entire tree
   */
  static extractTokens(node, tokens = { colors: new Set(), gradients: [], typography: new Map(), shadows: new Set() }) {
    if (!node || node.visible === false) return tokens;

    // 1. Colors & Gradients
    if (Array.isArray(node.fills)) {
      for (const fill of node.fills) {
        if (fill.visible === false) continue;
        if (fill.type === 'SOLID' && fill.color) {
          tokens.colors.add(FigmaCompiler.colorToCss(fill.color, fill.opacity));
        } else if (fill.type === 'GRADIENT_LINEAR') {
          const stops = (fill.gradientStops || [])
            .map((s) => `${FigmaCompiler.colorToCss(s.color)} ${Math.round((s.position || 0) * 100)}%`)
            .join(', ');
          tokens.gradients.push(`linear-gradient(135deg, ${stops})`);
        }
      }
    }

    // 2. Shadows
    if (Array.isArray(node.effects)) {
      const parsed = FigmaCompiler.parseEffects(node.effects);
      if (parsed.shadowCss && parsed.shadowCss !== 'none') {
        tokens.shadows.add(parsed.shadowCss);
      }
    }

    // 3. Typography
    if (node.type === 'TEXT' && node.style) {
      const key = `${node.style.fontFamily || 'Inter'}_${node.style.fontSize || 16}_${node.style.fontWeight || 400}`;
      if (!tokens.typography.has(key)) {
        tokens.typography.set(key, {
          fontFamily: node.style.fontFamily || 'Inter',
          fontSize: node.style.fontSize || 16,
          fontWeight: node.style.fontWeight || 400,
          lineHeightPx: node.style.lineHeightPx || 24,
          letterSpacing: node.style.letterSpacing || 0,
        });
      }
    }

    if (Array.isArray(node.children)) {
      for (const child of node.children) {
        this.extractTokens(child, tokens);
      }
    }

    return tokens;
  }

  /**
   * Generate CSS Variables stylesheet (theme.css)
   */
  static generateCssVariables(tokens) {
    const lines = ['/* Auto-generated by ACL-ADLC Figma Token Generator (Layer 4) */', ':root {'];

    let colorIdx = 1;
    tokens.colors.forEach((color) => {
      lines.push(`  --color-token-${colorIdx++}: ${color};`);
    });

    let shadowIdx = 1;
    tokens.shadows.forEach((shadow) => {
      lines.push(`  --shadow-elevation-${shadowIdx++}: ${shadow};`);
    });

    lines.push('}');
    return lines.join('\n');
  }

  /**
   * Generate Tailwind Theme Extension Object
   */
  static generateTailwindConfig(tokens) {
    const colors = {};
    let idx = 1;
    tokens.colors.forEach((c) => {
      colors[`figma-${idx++}`] = c;
    });

    return {
      theme: {
        extend: {
          colors,
          boxShadow: Object.fromEntries(Array.from(tokens.shadows).map((s, i) => [`elevation-${i + 1}`, s])),
        },
      },
    };
  }

  /**
   * Compile and generate all tokens
   */
  static compile(figmaDoc) {
    const root = figmaDoc.document || figmaDoc;
    const tokens = this.extractTokens(root);
    const cssVariables = this.generateCssVariables(tokens);
    const tailwindConfig = this.generateTailwindConfig(tokens);

    return {
      tokens: {
        colors: Array.from(tokens.colors),
        gradients: tokens.gradients,
        typography: Array.from(tokens.typography.values()),
        shadows: Array.from(tokens.shadows),
      },
      cssVariables,
      tailwindConfig,
    };
  }
}

module.exports = { FigmaTokenGenerator };
